        lines+=['### All-time records','','These are descriptive records of the indexed works, not quality rankings. File size is not word count or reading time.','','| Record | Holder | Measure |','| --- | --- | --- |']
        if units:
            biggest=max(units,key=lambda u:u['primary_bytes']);lines.append(f"| Largest primary source | {self.link(biggest, '.')} | {biggest['primary_bytes']:,} bytes |")
