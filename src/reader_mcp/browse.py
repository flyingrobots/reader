def encoded(path):
    return quote(str(path).replace(os.sep, '/'), safe='/._-')


def label(value):
    return re.sub(r'[\r\n\t]+', ' ', str(value)).replace('\\', '\\\\').replace('[', '\\[').replace(']', '\\]').replace('|', '\\|').replace('<', '&lt;').replace('>', '&gt;')


def strings(value):
    if isinstance(value, str):
        return [value.strip()] if value.strip() else []
    if isinstance(value, list):
        return sorted({v.strip() for v in value if isinstance(v, str) and v.strip()}, key=str.casefold)
    return []


def calendar_day(value):
    try:
        if not isinstance(value, str):
            return None
        if len(value) == 10:
            return date.fromisoformat(value).isoformat()
        dt = datetime.fromisoformat(value.replace('Z', '+00:00'))
        return dt.astimezone(timezone.utc).date().isoformat() if dt.tzinfo else None
    except ValueError:
        return None


def week(day):
    if not day:
        return 'Unknown arrival week'
    d = date.fromisoformat(day)
    y, w, _ = d.isocalendar()
    monday = d - timedelta(days=d.weekday())
    return f'{y}-W{w:02} · {monday} to {monday + timedelta(days=6)}'


def yaml_name(value):
    """A frontmatter scalar: bare when plain (the default name stays byte-identical), else JSON-quoted."""
    return value if re.fullmatch(r'[A-Za-z][A-Za-z0-9 .()_-]*', value) else json.dumps(value, ensure_ascii=False)


class Browse:
    def __init__(self, root):
        self.root = Path(root).resolve(strict=True)
        self.library = self.root / 'library'
        self.output = self.root / 'indexes'
        self.bytes_read = 0
        self.diagnostics = []

    def read(self, path, limit):
        if path.is_symlink() or not path.resolve().is_relative_to(self.root):
            raise ValueError(f'Unsafe browse input: {path.name}')
        with path.open('rb') as f:
            data = f.read(limit)
        self.bytes_read += len(data)
        if self.bytes_read > MAX_METADATA_BYTES:
            raise ValueError('Browse metadata exceeds 32 MiB; no publication')
        return data

    def header(self, path):
        if not path.is_file():
            return {}
        data = self.read(path, MAX_HEADER + 1)
        try:
            return source_frontmatter(data)[0]
        except ValueError as exc:
            self.diagnostics.append({'path':path.relative_to(self.root).as_posix(), 'issue':str(exc)[:300]})
            return {}

    def scan(self):
        result = {}
        count = 0
        if self.library.is_symlink():
            raise ValueError('Library must not be a symlink')
        for directory, dirs, files in os.walk(self.library, followlinks=False):
            dirs[:] = sorted(d for d in dirs if not d.startswith('.') and d not in SKIP)
            for name in dirs + files:
                p = Path(directory) / name
                count += 1
                if count > MAX_ENTRIES:
                    raise ValueError('Browse discovery exceeds 100,000 entries; no publication')
                if p.is_symlink():
                    raise ValueError('Symlink in browse discovery; reconcile before publication')
            for name in sorted(files):
                if os_junk(name):
                    continue
                if name == 'receipt.json' or Path(name).suffix.lower() in READABLE:
                    p = Path(directory) / name
                    stat = p.stat()
                    result[p.relative_to(self.root).as_posix()] = (stat.st_size, stat.st_mtime_ns)
        return result

    def inventory(self, settings):
        self.diagnostics = []
        snapshot = self.scan()
        meta = {}
        def metadata(path):
            rel = path.relative_to(self.root).as_posix()
            if rel not in meta:
                meta[rel] = self.header(path)
            return meta[rel]
        units = []
        receipts = []
        receipt_ids = set()
        groups = []
        covered = set()
        def make(path, m, *, title=None, author=None, arrival=None, basis=None,
                 project=None, kind=None, identity=None, primary=None):
            primary = primary or path
            source_authors = strings(author) or ['Unspecified author']
            author_aliases = settings.get('author_aliases', {})
            authors = sorted({name for raw in source_authors for name in (strings(author_aliases.get(raw.casefold(), raw)) or [raw])}, key=str.casefold)
            day = calendar_day(arrival)
            instant = datetime.fromisoformat(arrival.replace('Z', '+00:00')).astimezone(timezone.utc).isoformat() if day and isinstance(arrival, str) and len(arrival) > 10 else None
            title = title if isinstance(title, str) and title.strip() else m.get('title')
            title = title.strip() if isinstance(title, str) and title.strip() else primary.stem
            corpus = ' '.join([title, path.relative_to(self.library).as_posix(), *strings(m.get('tags')), *strings(m.get('topics'))]).casefold()
            topic_names = [r['name'] for r in settings.get('topics', []) if any(re.search(r'(?<!\w)' + re.escape(t.casefold()) + r'(?!\w)', corpus) for t in r['terms'])]
            topics = sorted(set(strings(m.get('topics')) + topic_names), key=str.casefold) or ['Unclassified topic']
            projects = strings(project)
            if not projects:
                projects = [r['name'] for r in settings.get('projects', []) if any(re.search(r'(?<!\w)' + re.escape(t.casefold()) + r'(?!\w)', corpus) for t in r['terms'])]
            aliases = settings.get('project_aliases', {})
            projects = sorted({aliases.get(p.casefold(), p) for p in projects}, key=str.casefold) or ['Unspecified project']
            genre = kind or m.get('writing_type') or m.get('type') or 'Unspecified type'
            genre = str(genre)
            if 'development-journal' in strings(m.get('tags')) and genre.casefold() in {'report', 'document', 'unspecified type'}:
                genre = 'Development journal'
            genre = settings.get('type_aliases', {}).get(genre.casefold(), genre)
            st = primary.stat()
            units.append({'id':identity or path.relative_to(self.root).as_posix(), 'title':title,
                          'path':path.relative_to(self.root).as_posix(), 'primary':primary.relative_to(self.root).as_posix(),
                          'authors':authors, 'source_authors':source_authors, 'topics':topics, 'projects':projects, 'types':[genre],
                          'date':day, 'arrival_time':instant, 'date_basis':basis if day else 'unknown', 'week':week(day),
                          'primary_bytes':st.st_size, 'primary_format':primary.suffix.lower()})
            if len(units) > MAX_WORKS:
                raise ValueError('Browse exceeds 10,000 work entries; no publication')
        # Receipts identify delivered works without hashing or loading their attachments.
        for rel in sorted(snapshot, key=lambda p:(len(Path(p).parts),p)):
            if Path(rel).name != 'receipt.json' or rel in covered:
                continue
            p = self.root / rel
            if p.stat().st_size > 128 * 1024:
                raise ValueError('Oversized browse receipt')
            r = json.loads(self.read(p, 128 * 1024))
            if not isinstance(r, dict) or r.get('reader_receipt') != 1:
                continue
            identity = r.get('id')
            if not isinstance(identity, str) or identity in receipt_ids:
                raise ValueError('Missing or duplicate browse receipt identity')
            receipt_ids.add(identity)
            primary = p.parent / relative_path(r['document'])
            descriptors = r.get('files')
            if not isinstance(descriptors, list) or not descriptors or len(descriptors) > 64:
                raise ValueError('Invalid browse receipt inventory')
            members = [p.parent / relative_path(f['path']) for f in descriptors]
            if primary not in members or not primary.is_file() or any(f.is_symlink() for f in members):
                raise ValueError('Missing or unsafe delivered primary')
            covered.update(f.relative_to(self.root).as_posix() for f in members)
            if any(not f.resolve().is_relative_to(p.parent.resolve()) for f in members):
                raise ValueError('Receipt payload escapes its delivery')
            sm = metadata(primary) if primary.suffix.lower() in {'.md','.markdown'} else {}
            wrapper = p.parent/'index.md'
            wm = metadata(wrapper)
            provenance = r.get('provenance') or {}
            merged = {**sm, **wm}
            if sm.get('type') and wm.get('kind') == 'catalog':
                merged['type'] = sm['type']
            make(wrapper if wrapper.is_file() else primary, merged, title=r.get('title'),
                 author=provenance.get('author') or wm.get('source_author') or sm.get('author'),
                 arrival=r.get('received_at'), basis='receipt received_at (UTC)',
                 project=provenance.get('project') or sm.get('project'), identity='receipt:'+identity,
                 primary=primary)
            receipts.append(p.parent)
        # Cataloged direct-drop packages count once; nested deliveries remain separate.
        for rel in sorted(snapshot, key=lambda p:(len(Path(p).parts),p)):
            p = self.root/rel
            if p.name != 'index.md' or len(p.parts)-len(self.root.parts) < 4:
                continue
            if any(p.is_relative_to(g) for g in receipts + groups):
                continue
            if any(g.is_relative_to(p.parent) for g in receipts):
                continue  # This is navigation over delivered works.
            m = metadata(p)
            package_author = m.get('source_author') or m.get('author')
            if m.get('kind') == 'catalog' and not m.get('source_author') and any(a.startswith('Reader librarian') for a in strings(package_author)):
                package_author = None
            originals = [f for pattern in ('*.pdf', '*.txt', 'originals/*.pdf', 'originals/*.txt') for f in p.parent.glob(pattern) if f.is_file() and not f.is_symlink()]
            primary = max(originals, key=lambda f:f.stat().st_size) if originals else p
            make(p, m, author=package_author, primary=primary,
                 arrival=m.get('added') or m.get('metadata_created'), basis='catalog filing date',
                 kind='Book' if p.relative_to(self.library).parts[0]=='books' else None,
                 project=m.get('project'))
            groups.append(p.parent)
        for rel in sorted(snapshot):
            p = self.root/rel
            if p.suffix.lower() not in READABLE or p.name == 'index.md':
                continue
            inside = any(p.is_relative_to(g) for g in receipts + groups)
            # Only explicitly identified original writing escapes package grouping.
            m = metadata(p) if p.suffix.lower() in {'.md','.markdown'} and (not inside or p.parent in receipts + groups) else {}
            if not m and not inside:
                sidecar = self.root/'catalog/metadata'/(p.relative_to(self.library).as_posix()+'.md')
                if sidecar.is_file():
                    m = metadata(sidecar)
            writing = bool(m.get('writing_type')) or bool(set(strings(m.get('tags'))) & {'librarian/writing','agy/writing','claude/writing'})
            if (inside and not writing) or rel in covered:
                continue
            if m.get('reading_source') or m.get('kind') in {'reading-copy','reading-record','intake-inspection','catalog'}:
                continue
            if p.name in AUX and not writing:
                continue
            make(p, m, author=m.get('author'), arrival=m.get('added') or m.get('metadata_created'),
                 basis='document filing date', project=m.get('project'))
        if self.scan() != snapshot:
            raise ValueError('Browse inputs changed during discovery; retry after filing')
        units.sort(key=lambda u:(u['title'].casefold(),u['id']))
        return units

    def settings(self):
        path = self.output/'settings.json'
        if not path.exists():
            return {}
        if path.stat().st_size > 128 * 1024:
            raise ValueError('Browse settings exceed 128 KiB')
        result = json.loads(self.read(path, 128 * 1024))
        if not isinstance(result, dict):
            raise ValueError('Browse settings must be an object')
        author = result.get('navigation_author', 'Reader librarian')
        if not isinstance(author, str) or not 0 < len(author.strip()) <= 100 or '\n' in author:
            raise ValueError('navigation_author must be a one-line name of 1–100 characters')
        self.navigation_author = author.strip()
        for key in ('topics','projects'):
            rules = result.get(key, [])
            if not isinstance(rules, list):
                raise ValueError('Browse rules must be lists')
            for item in rules:
                if (not isinstance(item, dict) or not isinstance(item.get('name'),str)
                        or not item['name'].strip() or not isinstance(item.get('terms'),list)
                        or not item['terms'] or any(not isinstance(t,str) or not t.strip() for t in item['terms'])):
                    raise ValueError('Browse rules need a name and nonblank terms')
        for key in ('author_aliases','project_aliases','type_aliases'):
            aliases = result.get(key, {})
            if not isinstance(aliases,dict) or any(not isinstance(k,str) for k in aliases):
                raise ValueError('Browse aliases must be string-keyed objects')
            for value in aliases.values():
                if key == 'author_aliases':
                    valid = bool(strings(value)) and (isinstance(value,str) or isinstance(value,list) and all(isinstance(v,str) and v.strip() for v in value))
                else:
                    valid = isinstance(value,str) and bool(value.strip())
                if not valid:
                    raise ValueError('Browse alias targets must be nonblank names')
        return result

    def link(self, u, prefix='..'):
        return f"[{label(u['title'])}]({prefix}/{encoded(u['path'])})"

