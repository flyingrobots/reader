    @contextmanager
    def locked(self):
        runtime=self.root/'.reader';runtime.mkdir(exist_ok=True)
        lock=runtime/'browse.lock'
        if runtime.is_symlink() or lock.is_symlink():raise ValueError('Unsafe browse runtime')
        with lock.open('a') as f:
            fcntl.flock(f,fcntl.LOCK_EX);yield

    def run(self, check=False, today=None):
        today=today or datetime.now(timezone.utc).date()
        with self.locked():
            if self.output.is_symlink() or (self.root/'README.md').is_symlink():raise ValueError('Unsafe browse output')
            self.bytes_read = 0
            settings=self.settings();units=self.inventory(settings)
            canonical=json.dumps({'units':units,'settings':settings,'diagnostics':self.diagnostics},sort_keys=True,ensure_ascii=False)
            generation=sha256(canonical.encode()).hexdigest()
            # Dates belong to this refresh, while the generation identifies metadata.
            outputs,groups=self.pages(units,generation,today)
            for name,svg in self.charts(units).items():outputs['assets/'+name]=svg+'\n'
            report={'generation':generation,'as_of':today.isoformat(),'work_entries':len(units),'metadata_bytes_read':self.bytes_read,'diagnostics':self.diagnostics,'works':units,'limits':{'metadata_bytes':MAX_METADATA_BYTES,'work_entries':MAX_WORKS,'output_bytes':MAX_OUTPUT_BYTES},'scope':'Grouped metadata navigation; payload integrity, complete source coverage, reading and global SQL/search freshness are not verified.'}
            outputs['coverage.json']=json.dumps(report,indent=2,ensure_ascii=False)+'\n'
            readme=self.root/'README.md';original=readme.read_text() if readme.exists() else '# Reader\n'
            if START in original or END in original:
                if original.count(START)!=1 or original.count(END)!=1 or original.index(START)>original.index(END):raise ValueError('Malformed README dashboard markers')
                before,tail=original.split(START);_,after=tail.split(END);new_readme=before+self.dashboard(units,groups,today)+after
            else:
                anchor='## What is Reader?'
                block=self.dashboard(units,groups,today)+'\n\n'
                new_readme=original.replace(anchor,block+anchor,1) if anchor in original else original.rstrip()+'\n\n'+block
            writes={self.output/name:text.encode() for name,text in outputs.items()};writes[readme]=new_readme.encode()
            if sum(len(v) for v in writes.values())>MAX_OUTPUT_BYTES:raise ValueError('Browse output exceeds 16 MiB; no publication')
            # Refuse overwriting an unrelated file or traversing a symlinked output parent.
            for path in writes:
                if any(p.is_symlink() for p in [path,*list(path.parents)[:len(path.parts)-len(self.root.parts)]]):raise ValueError('Symlink in browse output')
                if path.exists() and path.suffix=='.md' and path!=readme and MARKER not in path.read_text():raise ValueError('Refusing to overwrite an unowned browse page')
            changed=[str(p.relative_to(self.root)) for p,data in writes.items() if not p.exists() or p.read_bytes()!=data]
            if not check:
                for path,data in writes.items():
                    if str(path.relative_to(self.root)) not in changed:continue
                    path.parent.mkdir(parents=True,exist_ok=True)
                    fd,name=tempfile.mkstemp(prefix='.browse-',dir=path.parent)
                    try:
                        with os.fdopen(fd,'wb') as f:f.write(data)
                        os.replace(name,path)
                    finally:
                        if os.path.exists(name):os.unlink(name)
            return {'status':'stale' if check and changed else 'current','work_entries':len(units),'changed':changed,'metadata_bytes_read':self.bytes_read,'diagnostics':self.diagnostics,'generation':generation}
