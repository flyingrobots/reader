/* Build-time entry: emits the famous-theme stylesheet and its contrast adjustments. */
import {FAMOUS, famousId, resolveFamous} from './famous';
import {themeStylesheet} from './theme-css';

export function famousStylesheet(){
  const resolved=FAMOUS.map(resolveFamous),adjustments=resolved.flatMap(r=>r.adjustments);
  const header=['/* Generated by web/build.mjs from web_ui/famous-themes.json. Do not edit.',
    ' * Palettes are copied from their upstream sources (see THIRD_PARTY_NOTICES.md).',
    ' * Text colors that missed a contrast floor were moved in OKLCH lightness, hue held:',
    ...(adjustments.length?adjustments.map(a=>` *   ${a.theme} ${a.variant} --${a.token}: ${a.from} -> ${a.to}`):[' *   none']),' */'].join('\n');
  return {css:header+'\n'+themeStylesheet(resolved.map(r=>r.theme),(t,v)=>famousId(t.id,v)),adjustments};
}
